@app.cell
def _(df, land, mo):
    sub = df[df["country"] == land.value].sort_values("squeeze", ascending=False)
    mo.ui.table(sub, selection=None)
    return (sub,)


@app.cell
def _(sub):
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(7, 5))
