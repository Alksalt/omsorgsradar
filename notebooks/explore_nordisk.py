    ax.set_xlabel("Dekning hjemmetjeneste (%)")
    ax.set_ylabel("Vekst eldre befolkning (%)")
    ax.set_title("Dekning vs. eldrevekst")
    ax.axvline(sub["coverage"].median(), ls="--", lw=0.8, color="grey")
    ax.axhline(sub["growth_pct"].median(), ls="--", lw=0.8, color="grey")
    fig
    return ax, fig, plt


